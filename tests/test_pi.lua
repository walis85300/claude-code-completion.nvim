local buffer = require('claude-code-completion.buffer')
local pi = require('claude-code-completion.pi')
local source = require('claude-code-completion.source').new({})
local function check(ok, message)
  assert(ok, message)
  print('  PASS: ' .. message)
end

local root = vim.fn.tempname()
vim.fn.mkdir(root .. '/pi-editor-abc', 'p')
vim.fn.mkdir(root .. '/project/.pi/skills/example', 'p')
vim.fn.mkdir(root .. '/project/.pi/agents', 'p')
vim.fn.writefile({ '---', 'name: example', 'description: Example skill', '---' }, root .. '/project/.pi/skills/example/SKILL.md')
vim.fn.writefile({ '---', 'name: scout', 'description: Scout agent', '---' }, root .. '/project/.pi/agents/scout.md')
local original_cwd = vim.fn.getcwd()
vim.cmd.cd(vim.fn.fnameescape(root .. '/project'))
local buf = vim.api.nvim_create_buf(false, true)
vim.api.nvim_buf_set_name(buf, root .. '/pi-editor-abc/prompt.md')
vim.api.nvim_set_current_buf(buf)
check(buffer.get_host(buf) == 'pi', 'detect Pi external editor buffer')
check(source:enabled(), 'enable completion in Pi buffer')
local skills = pi.get_skills()
check(vim.tbl_contains(vim.tbl_map(function(s) return s.name end, skills), 'example'), 'discover project skill')
local agents = pi.get_agents()
check(vim.tbl_contains(vim.tbl_map(function(a) return a.name end, agents), 'scout'), 'discover project agent')
local result
source:get_completions({ line = '/skill:exam', cursor = { 1, 11 } }, function(r) result = r end)
check(vim.tbl_contains(vim.tbl_map(function(s) return s.label end, result.items), '/skill:example'), 'complete Pi skill syntax')
source:get_completions({ line = '@sc', cursor = { 1, 3 } }, function(r) result = r end)
check(not vim.tbl_contains(vim.tbl_map(function(s) return s.label end, result.items), '@scout'), 'do not offer non-native @agent syntax')
vim.api.nvim_buf_delete(buf, { force = true })
local other = vim.api.nvim_create_buf(false, true)
vim.api.nvim_buf_set_name(other, root .. '/project/prompt.md')
check(buffer.get_host(other) == nil, 'reject ordinary prompt.md')
vim.api.nvim_buf_delete(other, { force = true })
vim.cmd.cd(vim.fn.fnameescape(original_cwd))
vim.fn.delete(root, 'rf')
